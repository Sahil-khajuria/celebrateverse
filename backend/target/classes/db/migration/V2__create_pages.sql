CREATE TABLE birthday_pages (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    slug VARCHAR(50) UNIQUE NOT NULL,
    owner_user_id BIGINT NOT NULL,
    recipient_name VARCHAR(100),
    recipient_nickname VARCHAR(100),
    recipient_age INT,
    recipient_birthday DATE,
    favorite_color VARCHAR(50),
    favorite_music_genre VARCHAR(100),
    sender_name VARCHAR(100),
    sender_relationship VARCHAR(100),
    personal_message TEXT,
    theme VARCHAR(50) DEFAULT 'classic_gold',
    cake_theme VARCHAR(50) DEFAULT 'default',
    mode VARCHAR(20) DEFAULT 'QUICK',
    is_password_protected BOOLEAN DEFAULT FALSE,
    page_password_hash VARCHAR(255),
    reveal_at TIMESTAMP NULL,
    is_calm_mode_default BOOLEAN DEFAULT FALSE,
    view_count INT DEFAULT 0,
    is_published BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (owner_user_id) REFERENCES users(id) ON DELETE CASCADE
);
